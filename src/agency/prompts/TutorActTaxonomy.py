from enum import Enum


class TutorAct(Enum):
    """
    생성형 AI 활용 데이터 분석 학습에서 학습자 주도성(Student Agency) 지원을 위한 
    튜터 의도 분류체계
    
    명명 규칙: {카테고리약어}_{핵심행동} = {카테고리번호}{일련번호}
    - SE: Self-Efficacy (자기효능감)
    - MEL: Metacognition-Execution-Literacy (메타인지-수행-리터러시)
    - MER: Metacognition-Execution-Responsibility (메타인지-수행-책임의식)
    - IM: Intrinsic Motivation (내재적 동기)
    """

    # ---------------------------------------------------------
    # [10] 자기효능감(Self-Efficacy) - 원리 1: AI 활용 능력에 대한 자신감 구축
    # ---------------------------------------------------------
    SE_ACKNOWLEDGE = 11    # 능력 인정: 학습자의 AI 활용/과제 해결 방식을 긍정적으로 인정
    SE_GROWTH = 12        # 성장 강조: 성과와 발전을 구체적으로 강조하여 성장 인식
    SE_CONFIDENCE = 13    # 확신 부여: 어려운 과제도 단계적 접근으로 해결 가능함을 확신

    # =========================================================================
    # [30] 메타인지-수행-리터러시(Metacognition-Execution-Literacy) - 원리 3: 프롬프트 리터러시 함양
    # =========================================================================
    MEL_EXPLORE = 31      # 프롬프트 탐색: 다양한 질문(프롬프트) 방식을 탐색하도록 유도
    MEL_REFINE = 32       # 프롬프트 개선: AI 결과에 따라 프롬프트를 수정/개선하도록 판단 지원
    MEL_VERIFY = 33       # 결과 검증: AI 결과를 비판적으로 검증(출처, 사실 여부 등)하도록 요청

    # =========================================================================
    # [40] 메타인지-책임의식(Metacognition-Execution-Responsibility) - 원리 4: 책임의식 함양
    # =========================================================================
    MER_OWNERSHIP = 41    # 주체 의식: 학습 주체로서 노력을 AI에 위임하지 않도록 인지
    MER_BOUNDARY = 42     # 사용 경계: AI를 사용하지 말아야 할 시점/상황을 스스로 결정

    # =========================================================================
    # [60] 내재적 동기(Intrinsic Motivation) - 원리 6: 학습동기 강화
    # =========================================================================
    IM_DISCOVERY = 61    # 발견 즐거움: 새로운 지식 발견의 즐거움과 가치를 강조
    IM_ACHIEVEMENT = 62  # 성취감 강화: 과제 완수의 성취감을 충분히 느끼도록 지원
